// Writes THIRD_PARTY_NOTICES.md: licence texts of the runtime dependencies bundled into dist/searvex.mjs.
// Usage: node scripts/third-party-notices.mjs [--check]  (--check fails when the committed file is stale)
import fs from 'node:fs';
import path from 'node:path';

const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
const entries = Object.entries(lock.packages)
  .filter(([p, m]) => p && !m.dev && !m.devOptional)
  .map(([p, m]) => ({ dir: p, name: p.replace(/^.*node_modules\//, ''), version: m.version, license: m.license ?? 'UNKNOWN' }))
  .sort((a, b) => a.name.localeCompare(b.name));

const licenceText = (dir) => {
  const file = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  return file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : null;
};

const L = ['# Third-party notices', '', 'Searvex bundles the following runtime dependencies into `dist/searvex.mjs`. Their licences are reproduced', 'below as their terms require. Generated by `scripts/third-party-notices.mjs`; do not edit by hand.', ''];
const missing = [];
for (const e of entries) {
  const text = licenceText(e.dir);
  if (!text) missing.push(e.name);
  let fallback = '';
  if (!text) {
    const pkg = JSON.parse(fs.readFileSync(path.join(e.dir, 'package.json'), 'utf8'));
    const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name;
    fallback = `No licence file in the package. Declared licence: ${e.license} (https://spdx.org/licenses/${e.license}.html)${author ? `; copyright holder: ${author}` : ''}.`;
  }
  L.push(`## ${e.name} ${e.version} (${e.license})`, '', '```', text ?? fallback, '```', '');
}
const out = L.join('\n');
if (process.argv.includes('--check')) {
  const current = fs.existsSync('THIRD_PARTY_NOTICES.md') ? fs.readFileSync('THIRD_PARTY_NOTICES.md', 'utf8') : '';
  if (current !== out) {
    console.error('THIRD_PARTY_NOTICES.md is out of date: run node scripts/third-party-notices.mjs');
    process.exit(1);
  }
} else fs.writeFileSync('THIRD_PARTY_NOTICES.md', out);
console.log(`${entries.length} runtime packages${missing.length ? `; no licence file in: ${missing.join(', ')}` : ''}`);
